"""Build the office canteen's avocado history: two years of weekdays, what was on the menu,
the weather, events — and how many avocados were actually used. Regression target; the game asks
for next week's forecast.

Run: uv run --no-project data/build_avocados.py
Writes: server/datasets/avocados.ts
"""

import json
import math
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = 31
MENUS = {"avocado_toast": 46, "burrito_bowl": 38, "poke_bowl": 30, "pasta": 9, "schnitzel": 5}
WEEKDAY = [0.95, 1.05, 1.1, 1.0, 0.8]  # Mon … Fri (Friday: home office)


def main() -> None:
    rng = random.Random(SEED)
    columns = ["weekday", "month", "menu", "temp_c", "team_event", "holiday_week"]
    X, y = [], []
    d = date(2024, 9, 2)
    while d < date(2026, 9, 1):
        if d.weekday() < 5:
            menu = rng.choice(list(MENUS))
            season = math.sin((d.timetuple().tm_yday - 100) / 365 * 2 * math.pi)
            temp = round(12 + 10 * season + rng.gauss(0, 4), 1)
            event = int(rng.random() < 0.08)
            holiday = int(d.month in (8, 12) and rng.random() < 0.6)
            used = MENUS[menu] * WEEKDAY[d.weekday()] * (1 + 0.012 * (temp - 12)) * (0.55 if holiday else 1)
            used += 12 * event + rng.gauss(0, 3.5)
            X.append([d.weekday(), d.month, menu, temp, event, holiday])
            y.append(max(0, round(used)))
        d += timedelta(days=1)
    out = ROOT / "server/datasets/avocados.ts"
    out.write_text(
        "// Generated by data/build_avocados.py — do not edit.\n"
        f"// {len(y)} canteen weekdays, Sep 2024 – Aug 2026; target = avocados used.\n\n"
        f"export const columns = {json.dumps(columns)} as const;\n\n"
        f"export const menus = {json.dumps(list(MENUS))} as const;\n\n"
        "export const X: (string | number)[][] = [\n"
        + "".join(f"  {json.dumps(r)},\n" for r in X)
        + "];\n\n"
        + f"export const y: number[] = {json.dumps(y)};\n"
    )
    print(f"rows={len(y)} mean={sum(y) / len(y):.1f}")


if __name__ == "__main__":
    main()
