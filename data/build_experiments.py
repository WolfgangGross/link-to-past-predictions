"""Build the lab's experiment history: past research proposals (title, team, scale, compute, novelty)
and how many benchmark points they actually gained. TabPFN acts as a surrogate model and ranks
today's proposals, including from their free-text titles.

Run: uv run --no-project data/build_experiments.py
Writes: server/datasets/experiments.ts
"""

import json
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = 400
SEED = 23

TEAMS = ["scaling", "multimodal", "efficiency", "forecasting"]
# (title template, team, mean effect, extra spread)
IDEAS = [
    ("Chunked row attention for {n} rows", "scaling", 0.9, 0.4),
    ("Longer context via memory tokens", "scaling", 0.5, 0.6),
    ("Ablation: remove {part}", "scaling", -0.3, 0.2),
    ("Bigger model, same data", "scaling", 0.1, 0.3),
    ("Joint text encoder for free-text columns", "multimodal", 0.8, 1.0),
    ("Bigger tokenizer vocabulary", "multimodal", 0.0, 0.3),
    ("Image patches as extra columns", "multimodal", 0.3, 1.2),
    ("Ablation: freeze the text tower", "multimodal", -0.4, 0.2),
    ("Distill into a fast student", "efficiency", 0.4, 0.2),
    ("Quantize attention to int8", "efficiency", 0.2, 0.15),
    ("Prune half the heads", "efficiency", -0.1, 0.3),
    ("Calendar and lag features", "forecasting", 0.5, 0.2),
    ("Cross-series attention for related tables", "forecasting", 0.7, 0.9),
    ("Ablation: drop the date encoder", "forecasting", -0.3, 0.2),
]
PARTS = ["feature positional encodings", "the second attention block", "label smoothing", "the prior mixture"]


def main() -> None:
    rng = random.Random(SEED)
    columns = ["title", "team", "log10_rows", "gpu_days", "novelty"]
    X, y = [], []
    for _ in range(N):
        template, team, effect, spread = rng.choice(IDEAS)
        title = template.format(n=rng.choice(["100K", "1M", "10M"]), part=rng.choice(PARTS))
        log10_rows = round(rng.uniform(4.0, 6.5), 1)
        gpu_days = rng.randint(2, 40)
        novelty = rng.randint(1, 5)
        mean = (
            effect
            + (0.8 if team == "scaling" else 0.2) * (log10_rows - 4.0) * (1 if effect > 0 else 0.2)
            + 0.35 * math.log(gpu_days)
            + 0.15 * (novelty - 3)
            - 0.6
        )
        sd = 0.35 + spread + 0.15 * novelty
        X.append([title, team, log10_rows, gpu_days, novelty])
        y.append(round(rng.gauss(mean, sd), 2))
    out = ROOT / "server/datasets/experiments.ts"
    out.write_text(
        "// Generated by data/build_experiments.py — do not edit.\n"
        f"// {N} past experiments; target = benchmark points gained.\n\n"
        f"export const columns = {json.dumps(columns)} as const;\n\n"
        f"export const teams = {json.dumps(TEAMS)} as const;\n\n"
        "export const X: (string | number)[][] = [\n"
        + "".join(f"  {json.dumps(r)},\n" for r in X)
        + "];\n\n"
        + f"export const y: number[] = {json.dumps(y)};\n"
    )
    print(f"rows={N} mean_gain={sum(y) / N:.2f} hit_rate={sum(1 for v in y if v > 0.5) / N:.2f}")


if __name__ == "__main__":
    main()
