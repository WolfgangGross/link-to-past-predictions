"""Build the sick-kid dataset: what a child says in the morning, their temperature, and whether they
turned out to be contagious that day. Synthetic but with a known generating process, so the game
can sample honest outcomes. The `said` column is free text — TabPFN-3.5 reads it directly.

Run: uv run --no-project data/build_symptoms.py
Writes: server/datasets/symptoms.ts
"""

import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = 600
SEED = 7

# condition: (share, contagious-probability fn(days), temperature range, phrases)
PHRASES = {
    "flu": ["my head is hot", "everything hurts", "i feel shivery", "i'm cold and hot", "my head hurts so much", "i coughed all night"],
    "cold": ["my nose is runny", "*sniff*", "i sneeze a lot", "my throat tickles", "my nose is stuffy", "i coughed a bit"],
    "tummy_bug": ["my tummy is grumpy", "i threw up", "i feel sick in my tummy", "my tummy is gurgly", "i don't want breakfast"],
    "nothing": ["my tummy hurts", "i'm too tired", "i don't want to go", "my leg hurts", "can i stay home", "i feel funny"],
    "allergy": ["my eyes itch", "i sneeze a lot", "my nose tickles", "*sniff*", "my eyes are watery"],
}
FILLERS = ["", "", "", "mama, ", "papa, ", "*sniff* ", "ugh, "]


def sample(rng: random.Random) -> tuple[dict, str]:
    cond = rng.choices(["flu", "cold", "tummy_bug", "nothing", "allergy"], weights=[18, 30, 10, 27, 15])[0]
    test_today = rng.random() < 0.3
    # Kids with nothing wrong complain more on test days.
    if cond == "nothing" and not test_today and rng.random() < 0.5:
        cond = "allergy"
    days = rng.randint(0, 5)
    if cond == "flu":
        temp = rng.uniform(37.9, 39.6)
        contagious = rng.random() < (0.95 if days <= 3 else 0.6)
    elif cond == "cold":
        temp = rng.uniform(36.7, 37.8)
        contagious = rng.random() < (0.75 if days <= 2 else 0.25)
    elif cond == "tummy_bug":
        temp = rng.uniform(37.1, 38.6)
        contagious = rng.random() < 0.85
    elif cond == "nothing":
        temp = rng.uniform(36.3, 37.2)
        contagious = rng.random() < 0.03
    else:  # allergy
        temp = rng.uniform(36.4, 37.1)
        contagious = rng.random() < 0.05

    phrases = rng.sample(PHRASES[cond], k=rng.choice([1, 1, 2]))
    # Some cross-talk: symptoms overlap in real life.
    if rng.random() < 0.2:
        phrases.append(rng.choice(PHRASES[rng.choice(list(PHRASES))]))
    said = rng.choice(FILLERS) + " and ".join(phrases)
    row = {
        "said": said,
        "temperature_c": round(temp, 1),
        "days_since_onset": days,
        "test_today": int(test_today),
    }
    return row, "contagious" if contagious else "not_contagious"


def main() -> None:
    rng = random.Random(SEED)
    rows = [sample(rng) for _ in range(N)]
    columns = ["said", "temperature_c", "days_since_onset", "test_today"]
    rate = sum(1 for _, y in rows if y == "contagious") / N
    out = ROOT / "server/datasets/symptoms.ts"
    out.write_text(
        "// Generated by data/build_symptoms.py — do not edit.\n"
        f"// {N} synthetic school mornings; contagious in {rate:.1%}.\n\n"
        f"export const columns = {json.dumps(columns)} as const;\n\n"
        "export const X: (string | number)[][] = [\n"
        + "".join(f"  {json.dumps([r[c] for c in columns])},\n" for r, _ in rows)
        + "];\n\n"
        + f"export const y: string[] = {json.dumps([y for _, y in rows])};\n"
    )
    print(f"rows={N} contagious_rate={rate:.3f}")


if __name__ == "__main__":
    main()
