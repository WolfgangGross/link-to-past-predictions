"""Build the school-run dataset: door-to-gate minutes for three routes across Freiburg mornings.
Synthetic with a known process: rush-hour congestion on the main road, roadworks in the old town,
rain, and a heavy tail of incidents. Regression target, so TabPFN returns a full distribution.

Run: uv run --no-project data/build_traffic.py [rows]
Writes: server/datasets/traffic.ts
"""

import json
import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = int(sys.argv[1]) if len(sys.argv) > 1 else 20_000  # 100K fits in ~38 s: too slow for a live game
SEED = 11
ROUTES = ["car_main_road", "car_old_town", "bike_path"]


def minutes(rng: random.Random, route: str, depart: int, rain: int, roadworks: int) -> float:
    """depart = minutes after 7:00."""
    rush = math.exp(-((depart - 50) / 12) ** 2)  # peaks when leaving at 7:50
    if route == "car_main_road":
        t = 8 + 11 * rush + 3 * rain + rng.gauss(0, 1.2)
        if rng.random() < 0.06:
            t += rng.uniform(6, 25)  # accident, bin lorry, ...
    elif route == "car_old_town":
        t = 11 + 4 * rush + 7 * roadworks + 2 * rain + rng.gauss(0, 1.5)
        if rng.random() < 0.03:
            t += rng.uniform(4, 15)
    else:
        t = 13 + 1 * rush + 2.5 * rain + rng.gauss(0, 0.8)
        if rng.random() < 0.01:
            t += rng.uniform(5, 12)  # flat tyre
    return max(4.0, t)


def main() -> None:
    rng = random.Random(SEED)
    columns = ["route", "depart_min", "weekday", "rain", "roadworks_old_town"]
    X, y = [], []
    for _ in range(N):
        route = rng.choice(ROUTES)
        depart = rng.randint(25, 70)
        weekday = rng.randint(0, 4)
        rain = int(rng.random() < 0.2)
        roadworks = int(rng.random() < 0.25)
        X.append([route, depart, weekday, rain, roadworks])
        y.append(round(minutes(rng, route, depart, rain, roadworks), 1))
    out = ROOT / "server/datasets/traffic.ts"
    out.write_text(
        "// Generated by data/build_traffic.py — do not edit.\n"
        f"// {N:,} synthetic school runs (door to school gate, minutes).\n\n"
        f"export const columns = {json.dumps(columns)} as const;\n\n"
        f"export const routes = {json.dumps(ROUTES)} as const;\n\n"
        "export const X: (string | number)[][] = [\n"
        + "".join(f"{json.dumps(r, separators=(',', ':'))},\n" for r in X)
        + "];\n\n"
        + f"export const y: number[] = {json.dumps(y, separators=(',', ':'))};\n"
    )
    print(f"rows={N} mean={sum(y) / N:.1f} file={out.stat().st_size / 1e6:.1f}MB")


if __name__ == "__main__":
    main()
