"""Build the youth-football reinjury dataset: kids who played a match after an ankle sprain.
Small data (the physio's own records), classification target. Note: kids who want to play report
less pain than they feel — the pain score is a weak signal.

Run: uv run --no-project data/build_reinjury.py
Writes: server/datasets/reinjury.ts
"""

import json
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
N = 240
SEED = 5


def main() -> None:
    rng = random.Random(SEED)
    columns = ["age", "days_since_sprain", "swelling", "pain_reported", "minutes_planned", "previous_sprains"]
    X, y = [], []
    for _ in range(N):
        age = rng.randint(7, 13)
        days = rng.randint(1, 14)
        swelling = rng.choice([0, 0, 1, 1, 2, 3])
        prev = rng.choice([0, 0, 0, 1, 1, 2])
        minutes = rng.choice([15, 20, 30, 45, 60])
        true_pain = max(0, min(10, 2 * swelling + 4 - 0.35 * days + rng.gauss(0, 1.5)))
        pain = max(0, round(true_pain * rng.uniform(0.4, 1.0)))  # kids play it down
        logit = -2.8 + 0.85 * swelling - 0.22 * days + 0.45 * prev + 0.03 * minutes + 0.1 * true_pain - 0.05 * (age - 10)
        reinjured = rng.random() < 1 / (1 + math.exp(-logit))
        X.append([age, days, swelling, pain, minutes, prev])
        y.append("reinjured" if reinjured else "fine")
    out = ROOT / "server/datasets/reinjury.ts"
    out.write_text(
        "// Generated by data/build_reinjury.py — do not edit.\n"
        f"// {N} past youth matches played after an ankle sprain.\n\n"
        f"export const columns = {json.dumps(columns)} as const;\n\n"
        "export const X: number[][] = [\n"
        + "".join(f"  {json.dumps(r)},\n" for r in X)
        + "];\n\n"
        + f"export const y: string[] = {json.dumps(y)};\n"
    )
    print(f"rows={N} reinjury_rate={sum(1 for v in y if v == 'reinjured') / N:.3f}")


if __name__ == "__main__":
    main()
