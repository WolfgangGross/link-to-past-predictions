"""Build the umbrella-scene dataset from real Open-Meteo history (CC BY 4.0).

Each row is one morning in Freiburg at 07:00: the weather you can see from the
bedroom window. The label is whether it rains on the school run (08:00–09:00).

Run: uv run data/build_weather.py
Writes: server/datasets/weather.ts (training rows) and game/src/data/weather-mornings.ts
(held-out mornings the game uses as "today").
"""

import json
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAT, LON = 47.99, 7.85  # Freiburg im Breisgau
TRAIN_END = "2025-06-30"
HELD_OUT_END = "2025-12-31"
RAIN_MM = 0.2  # summed over the two school-run hours

VARS = [
    "temperature_2m",
    "relative_humidity_2m",
    "dew_point_2m",
    "pressure_msl",
    "cloud_cover",
    "wind_speed_10m",
    "precipitation",
]
COLUMNS = [
    "month",
    "temp_c",
    "humidity_pct",
    "dewpoint_spread_c",
    "pressure_hpa",
    "pressure_change_3h",
    "cloud_cover_pct",
    "wind_kmh",
    "rain_last_3h_mm",
]


def fetch() -> dict:
    query = urllib.parse.urlencode(
        {
            "latitude": LAT,
            "longitude": LON,
            "start_date": "2016-01-01",
            "end_date": HELD_OUT_END,
            "hourly": ",".join(VARS),
            "timezone": "Europe/Berlin",
        }
    )
    url = f"https://archive-api.open-meteo.com/v1/archive?{query}"
    with urllib.request.urlopen(url, timeout=120) as res:
        return json.load(res)


def build_rows(data: dict) -> list[tuple[str, list[float], str]]:
    hourly = data["hourly"]
    by_day: dict[str, dict[int, dict[str, float]]] = defaultdict(dict)
    for i, stamp in enumerate(hourly["time"]):
        day, hour = stamp[:10], int(stamp[11:13])
        by_day[day][hour] = {v: hourly[v][i] for v in VARS}

    rows = []
    for day, hours in sorted(by_day.items()):
        needed = [4, 5, 6, 7, 8, 9]
        if any(h not in hours or any(x is None for x in hours[h].values()) for h in needed):
            continue
        h7 = hours[7]
        # Open-Meteo precipitation is the sum over the preceding hour.
        school_run_mm = hours[8]["precipitation"] + hours[9]["precipitation"]
        features = [
            int(day[5:7]),
            round(h7["temperature_2m"], 1),
            round(h7["relative_humidity_2m"]),
            round(h7["temperature_2m"] - h7["dew_point_2m"], 1),
            round(h7["pressure_msl"], 1),
            round(h7["pressure_msl"] - hours[4]["pressure_msl"], 1),
            round(h7["cloud_cover"]),
            round(h7["wind_speed_10m"], 1),
            round(sum(hours[h]["precipitation"] for h in (5, 6, 7)), 1),
        ]
        rows.append((day, features, "rain" if school_run_mm >= RAIN_MM else "dry"))
    return rows


def main() -> None:
    rows = build_rows(fetch())
    train = [r for r in rows if r[0] <= TRAIN_END]
    held_out = [r for r in rows if r[0] > TRAIN_END]

    # "Today" candidates: grey held-out mornings. The game picks a few with an ambiguous rain chance.
    idx = {c: i for i, c in enumerate(COLUMNS)}
    mornings = [r for r in held_out if r[1][idx["cloud_cover_pct"]] >= 60]

    rain_rate = sum(1 for r in train if r[2] == "rain") / len(train)
    header = "// Generated by data/build_weather.py — do not edit.\n"
    header += "// Source: Open-Meteo historical weather API (CC BY 4.0), Freiburg im Breisgau.\n"

    server_file = ROOT / "server/datasets/weather.ts"
    server_file.parent.mkdir(parents=True, exist_ok=True)
    server_file.write_text(
        header
        + f"// {len(train)} mornings {train[0][0]} … {train[-1][0]}; rain on the school run in {rain_rate:.1%}.\n\n"
        + f"export const columns = {json.dumps(COLUMNS)} as const;\n\n"
        + "export const X: number[][] = [\n"
        + "".join(f"  {json.dumps(r[1])},\n" for r in train)
        + "];\n\n"
        + f"export const y: string[] = {json.dumps([r[2] for r in train])};\n"
    )

    game_file = ROOT / "game/src/data/weather-mornings.ts"
    game_file.parent.mkdir(parents=True, exist_ok=True)
    game_file.write_text(
        header
        + "// Held-out mornings (not in the training set) that the game uses as \"today\".\n\n"
        + "export const weatherMornings = [\n"
        + "".join(
            f"  {{ date: {json.dumps(r[0])}, features: {json.dumps(dict(zip(COLUMNS, r[1])))} }},\n"
            for r in mornings
        )
        + "];\n"
    )
    print(f"train={len(train)} rain_rate={rain_rate:.3f} held_out={len(held_out)} mornings={len(mornings)}")


if __name__ == "__main__":
    main()
